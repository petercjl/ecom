import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {nativeRegistry} from '../packages/ecom-cli/lib/sycm.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const file=path.join(root,'browser/ecom/sycm_read_registry.h');
const operations=nativeRegistry();
const json=JSON.stringify(operations),hash=crypto.createHash('sha256').update(json).digest('hex');
const content=`// Generated by ecom/gen-business-registry.mjs from the pinned MIT sycmcli snapshot.\n// Source attribution and license: packages/ecom-cli/lib/sycm-vendor.\n#ifndef BRAVE_BROWSER_ECOM_SYCM_READ_REGISTRY_H_\n#define BRAVE_BROWSER_ECOM_SYCM_READ_REGISTRY_H_\nnamespace ecom {\ninline constexpr char kSycmReadRegistry[] = R"ecom(${json})ecom";\ninline constexpr char kSycmReadRegistryHash[] = "${hash}";\n}  // namespace ecom\n#endif\n`;
if(process.argv.length!==3||!['--check','--write'].includes(process.argv[2]))throw Error('Use --check or --write');
if(process.argv[2]==='--check') {
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content)throw Error('Native business registry differs from the pinned CLI catalog');
} else {
  if(fs.existsSync(file)) {
    const info=fs.lstatSync(file);if(!info.isFile()||info.isSymbolicLink())throw Error('Unsafe generated target');
    const dir=path.join(root,'.local-backups','business-registry-'+crypto.randomUUID());fs.mkdirSync(dir,{mode:0o700});
    const backup=path.join(dir,'sycm_read_registry.h');fs.copyFileSync(file,backup,fs.constants.COPYFILE_EXCL);
    if(!fs.readFileSync(backup).equals(fs.readFileSync(file)))throw Error('Backup mismatch');
    fs.writeFileSync(file,content);
  } else fs.writeFileSync(file,content,{flag:'wx'});
}
console.log(`Native registry verified: ${Object.keys(operations).length} registered reads; ${hash}`);
