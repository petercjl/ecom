import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { git } from './workspace.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const pkg = JSON.parse(read('package.json'));
const baseline = JSON.parse(read('ecom/source-baseline.json'));
assert.equal(pkg.name, 'ecom-core');
for (const name of ['BRANDING', 'BRANDING.development']) {
  const branding = read('app/theme/brave/' + name);
  assert.match(branding, /^PRODUCT_FULLNAME=Ecom Dev$/m);
  assert.match(branding, /^MAC_BUNDLE_ID=app\.ecom\.browser\.dev$/m);
  assert.match(branding, /^MAC_TEAM_ID=$/m);
}
assert.equal(pkg.private, true);
assert.equal(pkg.config.siso_jobs_limit, 6);
for (const flag of ['symbol_level', 'v8_symbol_level', 'blink_symbol_level']) assert.equal(pkg.config.gn.args[flag], 0);
assert.equal(pkg.config.gn.args.concurrent_links, 1);
assert.equal(baseline.development.mode, 'independent-snapshot');
assert.equal(baseline.development.braveSynchronization, false);
assert.match(baseline.source.commit, /^[a-f0-9]{40}$/);
assert.equal(pkg.config.projects.chrome.tag, baseline.dependencies.chromium);
assert.equal(pkg.config.projects.chrome.custom_deps['src/third_party/swift-toolchain'], null);
assert.equal(pkg.config.projects.depot_tools.revision, baseline.dependencies.depotTools);
assert.equal(pkg.repository.url, 'https://github.com/petercjl/ecom.git');
assert.equal(pkg.scripts.sync, undefined);
for (const flag of ['enable_ai_chat', 'enable_brave_news', 'enable_brave_wallet', 'enable_updater', 'enable_sparkle', 'enable_update_notifications']) assert.equal(pkg.config.gn.args[flag], false);
const solutionWriter = read('build/commands/lib/syncUtils.js');
assert.ok(!solutionWriter.includes('https://github.com/brave/brave-core.git'));
assert.equal(solutionWriter.split(pkg.repository.url).length - 1, 2);
for (const name of ['BUILD.gn', 'browser/BUILD.gn', 'components/containers/core/browser/containers_service.h', 'LICENSE', 'assets/ecom-icon.png']) assert.ok(fs.statSync(path.join(root, name)).size > 0, name);
assert.match(read('LICENSE'), /Mozilla Public License Version 2.0/);
assert.ok(!fs.existsSync(path.join(root, 'src/main.cjs')));
const remotes = git(root, ['remote']).split('\n').filter(Boolean);
assert.deepEqual(remotes, ['origin']);
assert.match(git(root, ['remote', 'get-url', 'origin']), /github\.com[:/]petercjl\/ecom(?:\.git)?$/);
assert.ok(!read('AGENTS.md').includes('Electron'));
if (baseline.verification.nativeBuild) assert.ok(fs.statSync(path.join(root, baseline.verification.nativeBuildEvidence)).isFile());
console.log(JSON.stringify({ ok: true, project: 'Ecom', sourceRelease: baseline.source.release, sourceCommit: baseline.source.commit, chromium: baseline.dependencies.chromium, nativeBuildVerified: baseline.verification.nativeBuild, nativeBuildPlatforms: baseline.verification.nativeBuildPlatforms, nativeBuildExecutedByThisCheck: false, browserCLIImplemented: false }));
