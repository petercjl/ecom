import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { git } from './workspace.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const pkg = JSON.parse(read('package.json'));
const baseline = JSON.parse(read('ecom/source-baseline.json'));
assert.equal(pkg.name, 'ecom-core');
assert.equal(pkg.private, true);
assert.equal(baseline.development.mode, 'independent-snapshot');
assert.equal(baseline.development.braveSynchronization, false);
assert.match(baseline.source.commit, /^[a-f0-9]{40}$/);
assert.equal(pkg.config.projects.chrome.tag, baseline.dependencies.chromium);
assert.equal(pkg.config.projects.depot_tools.ref, baseline.dependencies.depotTools);
assert.equal(pkg.repository.url, 'https://github.com/petercjl/ecom.git');
assert.equal(pkg.scripts.sync, undefined);
for (const name of ['BUILD.gn', 'browser/BUILD.gn', 'components/containers/core/browser/containers_service.h', 'LICENSE', 'assets/ecom-icon.png']) assert.ok(fs.statSync(path.join(root, name)).size > 0, name);
assert.match(read('LICENSE'), /Mozilla Public License Version 2.0/);
assert.ok(!fs.existsSync(path.join(root, 'src/main.cjs')));
const remotes = git(root, ['remote']).split('\n').filter(Boolean);
assert.deepEqual(remotes, ['origin']);
assert.match(git(root, ['remote', 'get-url', 'origin']), /github\.com[:/]petercjl\/ecom(?:\.git)?$/);
assert.ok(!read('AGENTS.md').includes('Electron'));
console.log(JSON.stringify({ ok: true, project: 'Ecom', sourceRelease: baseline.source.release, sourceCommit: baseline.source.commit, chromium: baseline.dependencies.chromium, nativeBuildVerified: false, browserCLIImplemented: false }));
